import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(readFileSync(new URL("../design/tokens.json", import.meta.url), "utf8"));
const declarations = (values) => Object.entries(values).map(([key, value]) => `  --${key}: ${value};`).join("\n");
const css = `/* Generated by scripts/build-carnet-tokens.mjs. Edit design/tokens.json. */
:root {
${declarations(tokens.shared)}
}
:root:not([data-a11y="contraste"]) {
${declarations(tokens.light)}
  color-scheme: light;
}
:root[data-carnet-theme="nuit"]:not([data-a11y="contraste"]) {
${declarations(tokens.dark)}
  color-scheme: dark;
}
:root[data-a11y="contraste"] {
  --carnet-lavande: var(--surface);
  --carnet-rose: var(--surface);
  --carnet-sauge: var(--surface);
  --carnet-image-opacity: 0;
}
@media (prefers-contrast: more) {
  /* Match the night selector's specificity so accessibility wins the later cascade. */
  :root:not([data-a11y="nuit"]):not([data-a11y="nuit"]) {
${declarations(tokens.light)}
    --texte-doux: var(--texte);
    --bordure: var(--bordure-forte);
    --imagerie-opacite: 0;
    --carnet-image-opacity: 0;
    color-scheme: light;
  }
}
`;
const destination = new URL("../app/styles/carnet-tokens.css", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== css) throw new Error("Regenerate Carnet tokens with node scripts/build-carnet-tokens.mjs");
} else writeFileSync(destination, css);
